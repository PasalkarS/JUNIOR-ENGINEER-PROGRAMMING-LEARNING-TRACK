# String to Integer
age = "25"
age = int(age)

# String to Float
price = "99.50"
price = float(price)

# Integer to Float
number = 10
decimal_number = float(number)

# Float to Integer
value = 15.75
whole_number = int(value)

# Integer to String
score = 100
score_text = str(score)

print("Age:", age)
print("Price:", price)
print("Integer to Float:", decimal_number)
print("Float to Integer:", whole_number)
print("Integer to String:", score_text)
